// Regenerates prisma/schema.production.prisma (PostgreSQL) from prisma/schema.prisma
// (SQLite, the source of truth). Only the generator/datasource header differs.
// Run after every model change:  node scripts/sync-production-schema.mjs
import { readFileSync, writeFileSync } from "node:fs";

const source = readFileSync("prisma/schema.prisma", "utf-8");
const marker = "// ---------------------------------------------------------------------------\n// Accounts, roles, safety";
const bodyStart = source.indexOf(marker);
if (bodyStart === -1) throw new Error("Could not find the models marker in prisma/schema.prisma");

const header = `// KOSOVO 2036 — HUMAN NETWORK — production schema (Vercel deployment).
//
// GENERATED by scripts/sync-production-schema.mjs from prisma/schema.prisma
// (the SQLite schema local development uses). Do not edit by hand — change
// prisma/schema.prisma and re-run the script. Prisma ties a generated client
// to one database provider, so PostgreSQL gets its own generated client;
// src/lib/prisma.ts picks the client matching DATABASE_URL at runtime.

generator client {
  provider = "prisma-client-js"
  output   = "../src/generated/prisma-postgres"
}

datasource db {
  provider = "postgresql"
}

`;
writeFileSync("prisma/schema.production.prisma", header + source.slice(bodyStart));
console.log("prisma/schema.production.prisma regenerated");
